const EMPTY_ASSET_FILLERS = new Map([
    ['js', '/* Empty JavaScript asset generated by Rsbuild. */\n'],
    ['css', '/* Empty CSS asset generated by Rsbuild. */\n'],
]);

/**
 * 根据构建产物名称返回对应的最小合法内容。
 *
 * @param {string} assetName 构建产物相对路径
 * @returns {string | undefined} JS/CSS 占位内容，其他资源返回 undefined
 */
function getEmptyAssetFiller(assetName) {
    if (/\.(?:c|m)?js$/i.test(assetName)) return EMPTY_ASSET_FILLERS.get('js');
    if (/\.css$/i.test(assetName)) return EMPTY_ASSET_FILLERS.get('css');
    return undefined;
}

/**
 * 创建空构建资源填充插件。
 *
 * 插件仅在生产构建时生效，并在压缩完成、真实内容哈希计算之前填充 0 字节 JS/CSS。
 * 保留资源而不是删除资源，是为了避免 HTML 或异步 chunk 继续引用时产生 404。
 *
 * @returns {import('@rsbuild/core').RsbuildPlugin} Rsbuild 插件
 */
export function createEmptyAssetPlugin() {
    return {
        name: 'empty-asset-fallback',
        apply: 'build',
        setup(api) {
            api.processAssets(
                {
                    // summarize 位于 optimize-size 之后、optimize-hash 之前，
                    // 此时能够识别压缩后的空资源，并让最终 contenthash 覆盖填充内容。
                    stage: 'summarize',
                    targets: ['web'],
                },
                ({ assets, sources, compilation }) => {
                    const filledAssets = [];

                    for (const [assetName, asset] of Object.entries(assets)) {
                        const filler = getEmptyAssetFiller(assetName);
                        if (!filler || asset.size() !== 0) continue;

                        compilation.updateAsset(assetName, new sources.RawSource(filler));
                        filledAssets.push(assetName);
                    }

                    if (filledAssets.length > 0) {
                        api.logger.warn(
                            `已填充 ${filledAssets.length} 个 0 字节 JS/CSS 构建产物：\n` +
                                filledAssets.sort().map((name) => `- ${name}`).join('\n'),
                        );
                    }
                },
            );
        },
    };
}
